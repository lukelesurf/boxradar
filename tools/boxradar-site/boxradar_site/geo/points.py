"""Point references: airfields, runway axes, navigation fixes, towns.

These are CURATED, not filtered, and include/location.h records why:

    Markers and centrelines are deliberately separate lists: a marker is cheap
    orientation, whereas an extended centreline is a strong visual claim about
    where traffic is going. Mark plenty; draw centrelines only for the fields
    whose approach paths you actually care about.

So the bounding box is a search scope, never a selection. Pickers over
OurAirports and GeoNames are phase 4; this module is only the data path from
the selection config to the blob and to a header.

render_header() reproduces include/location.h's arrays. It is NOT used to
overwrite that file yet: the committed version carries an alternative-profile
example in comments, and losing prose to a generator is a bad trade before the
pickers exist to replace it. Phase 4 makes location.h generated output.
"""


def render_header(sel):
    """include/location.h's shape, from a selection config."""
    lines = [
        "// GENERATED by boxradar_site.geo — do not edit by hand.",
        "//",
        "// Which airfields, fixes and towns to draw. These are curated, not",
        "// filtered: a marker is cheap orientation, whereas an extended",
        "// centreline is a strong visual claim about where traffic is going.",
        "// Mark plenty; draw centrelines only for the fields whose approach",
        "// paths you actually care about.",
        "//",
        "// Everything here is published AIP data about public infrastructure.",
        "// Your own position (HOME_LAT/HOME_LON) deliberately lives in the",
        "// gitignored config.h instead, so a repo pushed to a public mirror",
        "// never carries your home coordinates.",
        "#pragma once",
        "",
        "// Airfield reference points, drawn as small SOLID squares with an",
        "// ICAO label. Usually the ARP, which is also the centre the CTR arcs",
        "// are struck from. Solid distinguishes them from the hollow squares",
        "// used for towns.",
        "struct AirfieldRef { float lat, lon; const char *name; };",
        "",
        "// Runway thresholds, for extended centrelines. Both ends: the axis is",
        "// taken from the two points rather than a published heading, so the",
        "// drawn line is guaranteed to pass through both runway ends and line",
        "// up with the airfield marker. Published headings sometimes disagree",
        "// with their own threshold coordinates by a degree or more.",
        "//",
        "// NOTE these are TRUE positions. Do not try to derive them from the",
        "// runway designator, which is MAGNETIC and rounded to 10 degrees.",
        "struct RunwayAxis { float lat0, lon0, lat1, lon1; };",
        "",
        "// Two kinds of fixed reference, distinguished by marker shape so they",
        "// are tellable apart at 5px without reading the label:",
        "//",
        "//   WAYPOINTS — navigation fixes: hollow TRIANGLE (chart convention)",
        "//   TOWNS     — ground references: hollow SQUARE",
        "//",
        "// Both are drawn under the traffic in the airspace grey, so an",
        "// aircraft label always wins where they collide.",
        "//",
        "// Short labels are better — every character is 6px and competes with",
        "// datablocks at close range — but real 5-letter fix identifiers are",
        "// kept intact rather than mangled into four, since a wrong label",
        "// costs more than six pixels. Neither array may be empty; comment the",
        "// whole block out instead, along with its draw call in scope.cpp.",
        "struct Waypoint { float lat, lon; const char *name; };",
        "struct TownRef { float lat, lon; const char *name; };",
        "",
    ]

    lines.append("static constexpr AirfieldRef AIRFIELDS[] = {")
    for name, lat, lon in sel.airfields:
        lines.append(f'    {{{lat:.5f}f, {lon:.5f}f, "{name}"}},')
    lines.append("};")
    lines.append("")

    lines.append("static constexpr RunwayAxis RUNWAYS[] = {")
    for lat0, lon0, lat1, lon1 in sel.runways:
        lines.append(f"    {{{lat0:.6f}f, {lon0:.6f}f, "
                     f"{lat1:.6f}f, {lon1:.6f}f}},")
    lines.append("};")
    lines.append("")

    lines.append("static constexpr Waypoint WAYPOINTS[] = {")
    for name, lat, lon in sel.waypoints:
        lines.append(f'    {{{lat:.5f}f, {lon:.5f}f, "{name}"}},')
    lines.append("};")
    lines.append("")

    lines.append("static constexpr TownRef TOWNS[] = {")
    for name, lat, lon in sel.towns:
        lines.append(f'    {{{lat:.5f}f, {lon:.5f}f, "{name}"}},')
    lines.append("};")
    lines.append("")
    return "\n".join(lines)
