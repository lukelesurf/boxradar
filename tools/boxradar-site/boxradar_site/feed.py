"""The one place that reads the receiver's aircraft feed.

Isolated for the same reason as upstream.py — server.py takes a fetcher
callable, so the route is tested without a network — but the two have opposite
characters and should not be merged. upstream.py crosses the internet over TLS
and is therefore cached hard. This is localhost over plain HTTP, regenerated by
readsb at about the rate the board polls, so it is fetched per request: a cache
here would add staleness and protect nothing.
"""

import json
import urllib.error
import urllib.request

# readsb writes it, lighttpd serves it, we read it back over the loopback
# rather than from disk: tar1090 owns the path layout, and going through HTTP
# means a tar1090 upgrade that moves the file is a 404 we can log rather than a
# silently empty scope.
FEED_URL = "http://127.0.0.1/tar1090/data/aircraft.json"


class FeedError(Exception):
    """Any failure to obtain a parsed aircraft list from the receiver."""


def fetch(timeout_s=2.0):
    """The feed's `aircraft` array, as raw dicts.

    Timeout is short by design: this is on the display's 1Hz path, and a poll
    that fails fast leaves the board's previous store on screen, where one that
    hangs would stall the request thread behind it.

    Unlike upstream.py, success is not logged. That one logs every fetch
    because the operational question is whether the cache went upstream; here
    the answer is always yes, once a second, and saying so would bury the
    failures in journald.
    """
    try:
        with urllib.request.urlopen(FEED_URL, timeout=timeout_s) as r:
            doc = json.load(r)
    except (urllib.error.URLError, TimeoutError, OSError) as e:
        print(f"feed: FAILED: {e}", flush=True)
        raise FeedError(f"fetch failed: {e}") from e
    except json.JSONDecodeError as e:
        print(f"feed: BAD JSON: {e}", flush=True)
        raise FeedError(f"bad JSON from the receiver: {e}") from e

    aircraft = doc.get("aircraft") if isinstance(doc, dict) else None
    if not isinstance(aircraft, list):
        print("feed: BAD SHAPE: no aircraft array", flush=True)
        raise FeedError("feed has no aircraft array")
    return aircraft
