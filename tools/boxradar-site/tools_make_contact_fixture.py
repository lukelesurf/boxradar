#!/usr/bin/env python3
"""Generate test/test_contact_feed/fixture_contacts.h — a real payload.

The contact feed has two independent implementations: the writer here and the
reader in lib/radarcore/contact_feed.cpp. Unit tests on either side cannot
catch a disagreement between them, because each is self-consistent — a field
at the wrong offset in both passes both suites. This fixture is the only test
that crosses the boundary.

A byte array rather than a file the C++ test opens, for the same reason as
tools_make_fixture.py: Unity tests run with an unpredictable working directory.
tests/test_fixture_current.py asserts this stays regenerable.
"""

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from boxradar_site import contacts  # noqa: E402

HOME_LAT, HOME_LON = 51.8850, 0.2350

# One degree of latitude is 60nm, so these ranges are exact by construction.
# Deliberately out of range order: the writer sorts, and a fixture already in
# order would not prove it.
FEED = [
    {"hex": "406b9e", "lat": HOME_LAT + 12.0 / 60, "lon": HOME_LON,
     "seen": 8.0, "flight": "MLAT01", "type": "mlat", "geom_rate": 1024,
     "alt_baro": 4000, "rssi": -30.5},
    {"hex": "4ca1d2", "lat": HOME_LAT + 6.0 / 60, "lon": HOME_LON,
     "seen": 3.0, "flight": "RYR12QD ", "t": "B738", "squawk": "7000",
     "alt_baro": 12000, "gs": 320.5, "track": 270.3, "baro_rate": -1088,
     "rssi": -12.5},
    # Dropped by the cap, so total and count differ in the fixture.
    {"hex": "3fcafe", "lat": HOME_LAT + 30.0 / 60, "lon": HOME_LON,
     "seen": 1.0, "flight": "FARAWAY", "alt_baro": 38000},
    # A callsign that fills the field exactly: the NUL can only come from the
    # reader, which is the case a fixed-width format gets wrong.
    {"hex": "400001", "lat": HOME_LAT + 1.0 / 60, "lon": HOME_LON,
     "seen": 0.5, "flight": "ABCDEFGH", "t": "A21N", "squawk": "0100",
     "alt_baro": 2500, "gs": 180.0, "track": 45.0},
    {"hex": "~a1b2c3", "lat": HOME_LAT + 2.0 / 60, "lon": HOME_LON,
     "seen": 2.0, "flight": "GNDCREW", "t": "B788", "alt_baro": "ground",
     "rssi": -5.0},
]

LIMIT = 4  # five valid contacts, so the farthest is capped away


def render(data):
    lines = [
        "// GENERATED by tools/boxradar-site/tools_make_contact_fixture.py",
        "// A real contact feed payload. Regenerate with that script;",
        "// tests/test_fixture_current.py fails if it drifts.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"// home {HOME_LAT}, {HOME_LON}; limit {LIMIT}",
        f"static const uint32_t CONTACT_FIXTURE_LEN = {len(data)};",
        "static const uint8_t CONTACT_FIXTURE[] = {",
    ]
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    data = contacts.build(FEED, HOME_LAT, HOME_LON, LIMIT)
    repo = pathlib.Path(__file__).resolve().parents[2]
    out = repo / "test" / "test_contact_feed" / "fixture_contacts.h"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(data))
    print(f"wrote {out} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
