// ---------------------------------------------------------------------------
// Per-board settings, selected by the build flag its PlatformIO env sets.
//
// One board needs only the block below. For a second board, add another
// `#elif defined(BOXRADAR_SITE_<NAME>)` here and a matching pair of envs in
// platformio.ini — see the `stansted` / `southend` pairs there. Keeping the
// site data and the OTA address in one env name is what stops the two
// drifting apart, because flashing the wrong pair fails *silently*: a board
// rejects any blob not built for its own home (GEO_HOME_TOLERANCE_DEG, ~11m,
// in lib/radarcore/geoblob.h) and simply carries on drawing its cached map.
//
// HOME_LAT/LON must match `home_lat`/`home_lon` in the site's selection JSON
// to within that ~11m. Four decimal places is the minimum that fits; three is
// 111m and every blob the board ever fetches is rejected, with no error
// beyond a line on the status row.
//
// RECEIVER_URL is the boxradar-site contact feed, NOT tar1090 directly. The
// board appends "?lat=&lon=&n=" and gets back fixed-size binary records the Pi
// has already filtered, range-sorted and capped — see
// docs/superpowers/specs/2026-08-08-contact-feed.md. Pointing this at
// aircraft.json will not work: the board no longer parses JSON traffic.
//
// The URL's last path segment names the METAR station, and METAR_STATION must
// match it — the firmware picks that id out of the response's "stations"
// array.
// ---------------------------------------------------------------------------
#if defined(BOXRADAR_SITE_HOME)

#define DEFAULT_RECEIVER_URL  "http://receiver.lan:8081/contacts"
#define DEFAULT_HOME_LAT      51.5000
#define DEFAULT_HOME_LON      -0.1000
#define DEFAULT_OTA_HOSTNAME  "boxradar"
#define DEFAULT_METAR_URL     "http://receiver.lan:8081/metar/EGSS"
#define DEFAULT_METAR_STATION "EGSS"
#define DEFAULT_GEO_URL       "http://receiver.lan/site.bin"

#else
#error "No site selected. Build a site env, e.g. -e home or -e home-usb."
#endif

#define DEFAULT_POLL_INTERVAL_MS 2000

// Optional weather, proxied by tools/boxradar-site on the receiver Pi. Comment
// out METAR_ENABLED and the site block's METAR_URL to disable; the status line
// simply omits the weather segments and everything else carries on.
#define METAR_ENABLED
// METARs are issued half-hourly and the proxy caches each station for 5
// minutes, so there is nothing to gain from polling this hard.
#define DEFAULT_METAR_POLL_INTERVAL_MS 60000

// Geography blob (airspace, coastline, airfields, fixes, towns),
// generated by boxradar_site.geo and served from the receiver Pi.
// Comment out to keep using the tables compiled into flash. The board
// caches the last good blob to LittleFS, so a Pi outage costs nothing.
#define GEO_ENABLED
#define DEFAULT_GEO_POLL_INTERVAL_MS 600000   // 10 min; it changes rarely


// ---------------------------------------------------------------------------
// The four below used to be build switches. They are now DEFAULTS for the
// runtime settings `coaston`, `ohon`, `nighton` and `nclkon`, which the Pi's
// Device page can change without a reflash. Both paths are compiled either
// way — measured at 1368 bytes of flash for all four — so commenting one out
// no longer removes any code, it just starts the board with that feature off.
//
// Change one here and the board must have no NVS override for it, or nothing
// happens: NVS shadows a compiled default permanently and silently. The
// Device page's "use built-in default" tick box is what removes the override.
// ---------------------------------------------------------------------------

// Draw the OSM coastline under everything else — the map's most expensive
// layer by an order of magnitude, and pointless at a landlocked site. Under
// MAP_FROM_BLOB (below) the coast comes from the blob, so this is purely a
// default. WITHOUT that flag it also decides whether the generated table
// (~12KB of flash) is compiled at all, and then `coaston` cannot turn on what
// is not there. Regenerate the table with
// `python3 -m boxradar_site.geo build --coastline-out ...` after moving, or it
// will keep drawing the previous area's coast.
#define DRAW_COASTLINE

// "OVHD <callsign> <n>s" readout in the top-left corner, predicting the
// next aircraft to pass close to overhead. The three thresholds behind it are
// settings too — see lib/radarcore/overhead.h, which also says how to drop
// the whole feature from the tree.
#define OVERHEAD_PREDICTION

// Blank the display overnight, waking on a tap. Needs NTP: the board has no
// RTC, and until the first sync lands it deliberately stays lit rather than
// sitting dark and looking dead. Off, the board never asks for the time at
// all — nothing else on it reads a wall clock.
#define NIGHT_BLANKING
#define DEFAULT_NIGHT_START_HOUR 0
#define DEFAULT_NIGHT_END_HOUR 7        // set equal to START to disable the window
#define DEFAULT_NIGHT_WAKE_S 30         // how long a tap holds the display up
#define DEFAULT_NIGHT_FADE_MS 600       // 0 snaps instead of fading
// Show a dim clock overnight instead of a black screen. Subordinate to
// NIGHT_BLANKING: with nothing going dark there is nothing for a clock to
// appear on. The duty is ABSOLUTE (0-255) and bypasses the LDR: at these
// levels the LDR's own floor (BL_MIN_DUTY, 40) is far too bright.
#define NIGHT_CLOCK
#define DEFAULT_NIGHT_CLOCK_DUTY 7
#define DEFAULT_NTP_SERVER "pool.ntp.org"   // or your router / LAN time server
// POSIX TZ rule, not an offset, so DST transitions are handled for good.
// UK: "GMT0BST,M3.5.0/1,M10.5.0". US Eastern: "EST5EDT,M3.2.0,M11.1.0".
#define DEFAULT_NIGHT_TZ "GMT0BST,M3.5.0/1,M10.5.0"

// Values above are DEFAULTS. NVS overrides them at boot; this pulls in the
// accessors (HOME_LAT, METAR_URL, ...) that read the live config, so every
// use site keeps its original spelling. NVS is an overlay, never a
// replacement — an empty NVS behaves exactly like these defaults.

// Draw the map from the runtime blob rather than the tables compiled into
// flash. Verified on hardware 2026-08-08. Comment out to fall back to the
// generated headers, which stay in the repo as regenerable output — the
// blob path saves ~20KB of flash but means no map at all if there is
// neither a cached blob nor a reachable GEO_URL.
#define MAP_FROM_BLOB

